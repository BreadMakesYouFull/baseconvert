#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Convert rational numbers between positive integer bases.

The core conversion uses exact rational arithmetic. Fractional output digits
are generated by repeated multiplication of the remainder by the output base;
repeated remainders identify the exact start of a repetend.

>>> base("0.3", 10, 2, string=True, exact=True)
'0.0[1001]'
>>> base("-FF.8", 16, 10, string=True, exact=True)
'-255.5'
>>> base("0.1", 3, 10, string=True, exact=True)
'0.[3]'
>>> base("0.125", 10, 16, string=True, exact=True)
'0.2'
>>> base(Fraction(1, 3), 10, 10, string=True, exact=True)
'0.[3]'
>>> base(("-", 1, 0, ".", 1), 2, 10, string=True, exact=True)
'-2.5'
>>> base("0.3", 10, 2, string=True, max_depth=4, recurring=False)
'0.0100'
"""

from fractions import Fraction
from math import gcd
from typing import Any, Iterable, Literal, TypeAlias

MAX_DEPTH: int = 128
Digit: TypeAlias = int | str
DigitTuple: TypeAlias = tuple[Digit, ...]
IntegerDigit: TypeAlias = int | Literal["-", "+"]


class BaseConverter:
    """Callable converter retaining the historical constructor and attributes."""

    def __init__(
        self,
        input_base: int,
        output_base: int,
        max_depth: int = 10,
        string: bool = False,
        recurring: bool = True,
        padding: int = 0,
        exact: bool = False,
    ) -> None:
        self.input_base: int = input_base
        self.output_base: int = output_base
        self.max_depth: int = 0 if exact else max_depth
        self.string: bool = string
        self.recurring: bool = recurring
        self.padding: int = padding

    def __call__(self, number: Any) -> str | DigitTuple:
        return base(
            number,
            self.input_base,
            self.output_base,
            self.max_depth,
            self.string,
            self.recurring,
            self.padding,
        )


def represent_as_tuple(string: str) -> DigitTuple:
    """Represent digit text as a tuple of integer digit values."""
    keep = (".", "[", "]", "-", "+")
    return tuple(str_digit_to_int(c) if c not in keep else c for c in string)


def represent_as_string(iterable: Iterable[Digit]) -> str:
    """Represent a sequence of digits as text."""
    keep = (".", "[", "]", "-", "+")
    return "".join(int_to_str_digit(i) if i not in keep else i for i in iterable)


def pad(iterable: str | Iterable[Digit], n: int) -> str | DigitTuple:
    """Left-pad the integer part of a string or digit sequence with zeroes."""
    if isinstance(iterable, str):
        integer_part = iterable.split(".", 1)[0]
        return "0" * max(0, n - len(integer_part)) + iterable
    iterable = tuple(iterable)
    point = iterable.index(".") if "." in iterable else len(iterable)
    return ("0",) * max(0, n - point) + iterable


def digit(decimal: int, digit: int, input_base: int = 10) -> int:
    """Return the value at a zero-indexed position in a positive integer."""
    if decimal == 0:
        return 0
    return (decimal // (input_base**digit)) % input_base


def digits(number: int, base: int = 10) -> int:
    """Return the number of digits in a non-negative integer."""
    if number < 1:
        return 0
    count = 0
    while number:
        number //= base
        count += 1
    return count


def integer_fractional_parts(
    number: DigitTuple,
) -> tuple[DigitTuple, DigitTuple]:
    """Return the integer and fractional slices of a digit sequence."""
    radix_point = number.index(".")
    return number[:radix_point], number[radix_point:]


def from_base_10_int(decimal: int, output_base: int = 10) -> DigitTuple:
    """Convert an integer to a tuple of digits in ``output_base``."""
    if not isinstance(decimal, int):
        raise TypeError("decimal must be an integer")
    if not isinstance(output_base, int) or output_base < 1:
        raise ValueError("base must be a positive integer")
    sign: DigitTuple = ("-",) if decimal < 0 else ()
    decimal = abs(decimal)
    if decimal == 0:
        return (0,)
    if output_base == 1:
        return sign + (1,) * decimal
    result: list[int] = []
    while decimal:
        decimal, remainder = divmod(decimal, output_base)
        result.append(remainder)
    return sign + tuple(reversed(result))


def to_base_10_int(n: Iterable[IntegerDigit], input_base: int) -> int:
    """Convert integer digits, optionally prefixed by a sign, to an integer."""
    n = tuple(n)
    sign = 1
    if n and n[0] in ("-", "+"):
        sign = -1 if n[0] == "-" else 1
        n = n[1:]
    if input_base == 1:
        return sign * sum(value == 1 for value in n)
    value = 0
    for digit_value in n:
        value = value * input_base + digit_value
    return sign * value


def integer_base(
    number: Iterable[IntegerDigit], input_base: int = 10, output_base: int = 10
) -> DigitTuple:
    """Convert an integer digit sequence between bases."""
    return from_base_10_int(to_base_10_int(number, input_base), output_base)


def fractional_base(
    fractional_part: DigitTuple,
    input_base: int = 10,
    output_base: int = 10,
    max_depth: int = 10,
) -> DigitTuple:
    """Convert a fractional digit sequence, limited to ``max_depth`` digits."""
    if input_base < 2 or output_base < 2:
        raise ValueError("fractional conversion requires bases of at least 2")
    digits_in = tuple(fractional_part[1:])
    denominator = input_base ** len(digits_in)
    numerator = 0
    for value in digits_in:
        numerator = numerator * input_base + value
    result: list[Digit] = ["."]
    remainder = numerator
    for _ in range(max_depth):
        digit_value, remainder = divmod(remainder * output_base, denominator)
        result.append(digit_value)
        if remainder == 0:
            break
    return tuple(result)


def truncate(n: Iterable[Digit]) -> DigitTuple:
    """Remove trailing fractional zeroes, preserving the radix point."""
    n = tuple(n)
    if "." not in n:
        return n
    while len(n) > n.index(".") + 1 and n[-1] == 0:
        n = n[:-1]
    return n


def str_digit_to_int(chr: str) -> int:
    """Convert a character to its digit value (0-9, A-Z, a-z, then Unicode)."""
    if "0" <= chr <= "9":
        return ord(chr) - ord("0")
    value = ord(chr)
    if value < 91:
        return value - 55
    return value - 61


def int_to_str_digit(n: int) -> str:
    """Convert a non-negative digit value to its character representation."""
    if n < 10:
        return str(n)
    if n < 36:
        return chr(n + 55)
    return chr(n + 61)


def find_recurring(number: Iterable[Digit], min_repeat: int = 5) -> DigitTuple:
    """Find a repeated suffix pattern in a finite fractional digit sequence.

    Kept for compatibility. The main converter now finds repetends exactly
    from rational remainders instead of using this heuristic.
    """
    number = tuple(number)
    if "." not in number or min_repeat < 1:
        return number
    point = number.index(".")
    fraction = number[point + 1 :]
    for period in range(1, len(fraction) // (min_repeat + 1) + 1):
        repetitions = 1
        while (repetitions + 1) * period <= len(fraction) and all(
            fraction[-period:]
            == fraction[-(repetitions + 1) * period : -repetitions * period]
        ):
            repetitions += 1
        if repetitions > min_repeat:
            start = len(number) - repetitions * period
            return number[:start] + ("[",) + number[start:] + ("]",)
    return number


def expand_recurring(number: Iterable[Digit], repeat: int = 5) -> DigitTuple:
    """Expand a bracketed recurring pattern ``repeat`` additional times."""
    number = tuple(number)
    if "[" not in number:
        return number
    start = number.index("[")
    end = number.index("]", start)
    pattern = number[start + 1 : end]
    return number[:start] + pattern * (repeat + 1) + number[end + 1 :]


def check_valid(number: Iterable[Digit], input_base: int = 10) -> bool:
    """Return whether the numeral has valid digits and syntax for its base."""
    if not isinstance(input_base, int) or input_base < 1:
        return False
    try:
        number = tuple(number)
    except TypeError:
        return False
    if number and number[0] in ("-", "+"):
        number = number[1:]
    if any(value in ("-", "+") for value in number):
        return False
    if number.count(".") > 1:
        return False
    if number.count("[") != number.count("]") or number.count("[") > 1:
        return False
    if "[" in number:
        if "." not in number or number.index("[") <= number.index("."):
            return False
        if number[-1] != "]" or number.index("]") != len(number) - 1:
            return False
        if number.index("[") + 1 == number.index("]"):
            return False
    elif "]" in number:
        return False
    for value in number:
        if value in (".", "[", "]"):
            continue
        if not isinstance(value, int) or value < 0 or value >= input_base:
            if input_base == 1 and value == 1:
                continue
            return False
    if input_base == 1:
        return (
            "." not in number
            and "[" not in number
            and all(value in (0, 1) for value in number)
        )
    return True


def _digits_value(digit_values: Iterable[int], input_base: int) -> int:
    value = 0
    for digit_value in digit_values:
        value = value * input_base + digit_value
    return value


def _number_as_fraction(number: Any, input_base: int) -> Fraction:
    """Parse a numeral exactly, including an optional repetend and sign."""
    if isinstance(number, Fraction):
        return number
    if isinstance(number, (int, float)):
        number = str(number)
    if isinstance(number, str):
        number = represent_as_tuple(number)
    else:
        number = tuple(number)

    sign = 1
    if number and number[0] in ("-", "+"):
        sign = -1 if number[0] == "-" else 1
        number = number[1:]
    if not number or not check_valid(number, input_base):
        raise ValueError("invalid number or digit for input base")

    if input_base == 1:
        if "." in number or "[" in number:
            raise ValueError("fractional numerals are not supported in base 1")
        return Fraction(sign * sum(value == 1 for value in number), 1)

    if "[" in number:
        cycle_start = number.index("[")
        point = number.index(".")
        integer_digits = number[:point]
        prefix = number[point + 1 : cycle_start]
        cycle = number[cycle_start + 1 : -1]
        prefix_length = len(prefix)
        cycle_length = len(cycle)
        result = Fraction(_digits_value(integer_digits, input_base), 1)
        if prefix:
            result += Fraction(
                _digits_value(prefix, input_base), input_base**prefix_length
            )
        result += Fraction(
            _digits_value(cycle, input_base),
            input_base**prefix_length * (input_base**cycle_length - 1),
        )
        return sign * result

    if "." in number:
        point = number.index(".")
        integer_digits = number[:point]
        fractional_digits = number[point + 1 :]
    else:
        integer_digits = number
        fractional_digits = ()
    denominator = input_base ** len(fractional_digits)
    numerator = _digits_value(integer_digits, input_base) * denominator + _digits_value(
        fractional_digits, input_base
    )
    return sign * Fraction(numerator, denominator)


def _fraction_to_digits(
    value: Fraction, output_base: int, max_depth: int, recurring: bool
) -> DigitTuple:
    """Render a Fraction using positional division and exact remainder cycles."""
    if not isinstance(output_base, int) or output_base < 1:
        raise ValueError("base must be a positive integer")
    if not isinstance(max_depth, int) or max_depth < 0:
        raise ValueError("max_depth must be a non-negative integer")
    sign: DigitTuple = ("-",) if value < 0 else ()
    value = abs(value)
    if output_base == 1:
        if value.denominator != 1:
            raise ValueError("fractional values cannot be represented in base 1")
        return sign + ((1,) * value.numerator if value.numerator else (0,))

    integer_value, remainder = divmod(value.numerator, value.denominator)
    integer_digits = from_base_10_int(integer_value, output_base)
    fractional_digits: list[int] = []
    seen: dict[int, int] = {}
    repeat_at: int | None = None
    limit = max_depth if max_depth else (None if recurring else MAX_DEPTH)

    while remainder:
        if recurring and remainder in seen:
            repeat_at = seen[remainder]
            break
        if limit is not None and len(fractional_digits) >= limit:
            break
        if recurring:
            seen[remainder] = len(fractional_digits)
        digit_value, remainder = divmod(remainder * output_base, value.denominator)
        fractional_digits.append(digit_value)

    if not fractional_digits:
        return sign + integer_digits
    if repeat_at is not None:
        fractional = (
            tuple(fractional_digits[:repeat_at])
            + ("[",)
            + tuple(fractional_digits[repeat_at:])
            + ("]",
            )
        )
    else:
        fractional = tuple(fractional_digits)
    return sign + integer_digits + (".",) + fractional


def _pad_signed(result: DigitTuple, padding: int) -> DigitTuple:
    sign = result[:1] if result[:1] in (("-",), ("+",)) else ()
    body = result[len(sign) :]
    point = body.index(".") if "." in body else len(body)
    return sign + ("0",) * max(0, padding - point) + body


def base(
    number: Any,
    input_base: int = 10,
    output_base: int = 10,
    max_depth: int = 10,
    string: bool = False,
    recurring: bool = True,
    padding: int = 0,
    exact: bool = False,
) -> str | DigitTuple:
    """Convert a rational numeral between positive integer bases.

    ``number`` intentionally accepts a flexible set of inputs: strings, digit
    iterables, integers, floats, and ``Fraction`` instances. ``max_depth``
    limits fractional digits. ``exact=True`` or ``max_depth=0`` computes the
    full terminating or repeating expansion when ``recurring`` is enabled. If
    recurring output is disabled, an unlimited request is bounded by
    ``MAX_DEPTH`` for compatibility.
    """
    if not isinstance(input_base, int) or input_base < 1:
        raise ValueError("base must be a positive integer")
    if exact:
        max_depth = 0
    value = _number_as_fraction(number, input_base)
    result = _fraction_to_digits(value, output_base, max_depth, recurring)
    if string:
        sign = result[:1] if result[:1] in (("-",), ("+",)) else ()
        body = represent_as_string(result[len(sign) :])
        point = body.index(".") if "." in body else len(body)
        return represent_as_string(sign) + "0" * max(0, padding - point) + body
    return _pad_signed(result, padding)


